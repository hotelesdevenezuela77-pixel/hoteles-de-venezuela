-- Helper para actualizar updated_at automáticamente
CREATE OR REPLACE FUNCTION fn_update_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_properties_updated_at ON properties;
CREATE TRIGGER trg_properties_updated_at
    BEFORE UPDATE ON properties
    FOR EACH ROW
    EXECUTE FUNCTION fn_update_timestamp();

DROP TRIGGER IF EXISTS trg_property_units_updated_at ON property_units;
CREATE TRIGGER trg_property_units_updated_at
    BEFORE UPDATE ON property_units
    FOR EACH ROW
    EXECUTE FUNCTION fn_update_timestamp();

-- Función para Crear o Actualizar un Pre-Registro Rápido (Ficha Pública)
CREATE OR REPLACE FUNCTION fn_create_preregistered_property(
    p_service_category_id INT,
    p_subcategory_id INT,
    p_title VARCHAR(255),
    p_slug VARCHAR(255),
    p_destination_name VARCHAR(150),
    p_state VARCHAR(100),
    p_city VARCHAR(100),
    p_short_description TEXT,
    p_base_price_from NUMERIC(12,2),
    p_rating_avg NUMERIC(3,2),
    p_whatsapp_number VARCHAR(50),
    p_primary_image TEXT,
    p_has_power_plant BOOLEAN,
    p_has_water_247 BOOLEAN,
    p_has_starlink BOOLEAN,
    p_is_pet_friendly BOOLEAN,
    p_has_hdv_seal BOOLEAN,
    p_key_service_pills TEXT[]
)
RETURNS UUID AS $$
DECLARE
    v_property_id UUID;
    v_initial_features JSONB;
BEGIN
    -- Construir JSONB inicial con los atributos capturados en el pre-registro
    v_initial_features := jsonb_build_object(
        'pre_registration', jsonb_build_object(
            'captured_at', CURRENT_TIMESTAMP,
            'source', 'FICHA_PUBLICA_FAST_ONBOARDING'
        ),
        'badges', jsonb_build_object(
            'C03.4.1', p_has_power_plant,
            'C03.4.2', p_has_water_247,
            'C11.4.6', p_has_starlink,
            'C06.2.1', p_is_pet_friendly,
            'C00.5.9', p_has_hdv_seal
        ),
        'commercial', jsonb_build_object(
            'C00.1.1', p_title,
            'C00.1.9', p_short_description,
            'rating', p_rating_avg,
            'price_from', p_base_price_from,
            'pills', p_key_service_pills
        ),
        'contact', jsonb_build_object(
            'C00.3.2.6', p_whatsapp_number
        )
    );

    INSERT INTO properties (
        service_category_id,
        subcategory_id,
        title,
        slug,
        destination_name,
        state,
        city,
        short_description,
        base_price_from,
        rating_avg,
        whatsapp_number,
        primary_image,
        has_power_plant,
        has_water_247,
        has_starlink,
        is_pet_friendly,
        has_hdv_seal,
        key_service_pills,
        onboarding_status,
        status,
        features
    ) VALUES (
        p_service_category_id,
        p_subcategory_id,
        p_title,
        p_slug,
        p_destination_name,
        p_state,
        p_city,
        p_short_description,
        p_base_price_from,
        p_rating_avg,
        p_whatsapp_number,
        p_primary_image,
        p_has_power_plant,
        p_has_water_247,
        p_has_starlink,
        p_is_pet_friendly,
        p_has_hdv_seal,
        p_key_service_pills,
        'PRE_REGISTERED',
        'ACTIVE',
        v_initial_features
    )
    ON CONFLICT (slug) DO UPDATE SET
        title = EXCLUDED.title,
        destination_name = EXCLUDED.destination_name,
        state = EXCLUDED.state,
        city = EXCLUDED.city,
        short_description = EXCLUDED.short_description,
        base_price_from = EXCLUDED.base_price_from,
        rating_avg = EXCLUDED.rating_avg,
        whatsapp_number = EXCLUDED.whatsapp_number,
        primary_image = EXCLUDED.primary_image,
        has_power_plant = EXCLUDED.has_power_plant,
        has_water_247 = EXCLUDED.has_water_247,
        has_starlink = EXCLUDED.has_starlink,
        is_pet_friendly = EXCLUDED.is_pet_friendly,
        has_hdv_seal = EXCLUDED.has_hdv_seal,
        key_service_pills = EXCLUDED.key_service_pills,
        features = properties.features || v_initial_features,
        updated_at = CURRENT_TIMESTAMP
    RETURNING id INTO v_property_id;

    RETURN v_property_id;
END;
$$ LANGUAGE plpgsql;
